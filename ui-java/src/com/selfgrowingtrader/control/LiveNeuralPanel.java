        private static void appendDeepValue(StringBuilder out, Object value, String indent) {
            if (value instanceof Map<?, ?> rawMap) {
                Map<String, Object> map = MiniJson.object(rawMap);
                if (map.isEmpty()) { out.append(indent).append("—\n"); return; }
                for (Map.Entry<String, Object> entry : map.entrySet()) {
                    Object child = entry.getValue();
                    if (child instanceof Map<?, ?> || child instanceof List<?>) {
                        out.append(indent).append(dichNhan(entry.getKey())).append(":\n");
                        appendDeepValue(out, child, indent + "  ");
                    } else {
                        out.append(indent).append(dichNhan(entry.getKey())).append(": ").append(String.valueOf(child)).append('\n');
                    }
                }
                return;
            }
            if (value instanceof List<?> list) {
                if (list.isEmpty()) { out.append(indent).append("—\n"); return; }
                int index = 1;
                for (Object child : list) {
                    if (child instanceof Map<?, ?> || child instanceof List<?>) {
                        out.append(indent).append("[").append(index++).append("]\n");
                        appendDeepValue(out, child, indent + "  ");
                    } else {
                        out.append(indent).append("[").append(index++).append("] ").append(String.valueOf(child)).append('\n');
                    }
                }
                return;
            }
            out.append(indent).append(value == null ? "—" : String.valueOf(value)).append('\n');
        }

