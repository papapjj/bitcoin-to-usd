    private static final class LiveEventTailer {
        private Path currentPath;
        private long offset;

        void reset() {
            currentPath = null;
            offset = 0;
        }

        TailResult read(Path path, int maxLines, int maxBytes) {
            if (path == null) {
                return new TailResult(false, false, List.of(), "No event path");
            }
            try {
                if (!Files.exists(path)) {
                    boolean reset = currentPath != null && currentPath.equals(path) && offset > 0;
                    currentPath = path;
                    offset = 0;
                    return new TailResult(false, reset, List.of(), "");
                }
                long size = Files.size(path);
                boolean reset = !path.equals(currentPath) || size < offset;
                if (reset) {
                    currentPath = path;
                    offset = 0;
                }
                if (size <= offset) {
                    return new TailResult(true, reset, List.of(), "");
                }
                long remaining = size - offset;
                long requested = maxBytes <= 0 ? remaining : Math.min((long) maxBytes, remaining);
                // Không có giới hạn dữ liệu tổng. Tuy nhiên một snapshot topology
                // có thể dài vài MB, nên nếu chunk hiện tại chưa chứa newline,
                // nới dần đến hết một record thay vì đứng yên vô hạn.
                byte[] bytes = null;
                int actual = 0;
                int lastNewline = -1;
                int lines = 0;
                while (true) {
                    if (requested > Integer.MAX_VALUE) {
                        return new TailResult(false, reset, List.of(), "Một JSONL record vượt giới hạn byte-array của JVM");
                    }
                    int take = (int) requested;
                    bytes = new byte[take];
                    try (FileChannel channel = FileChannel.open(path, StandardOpenOption.READ)) {
                        channel.position(offset);
                        ByteBuffer buffer = ByteBuffer.wrap(bytes);
                        actual = channel.read(buffer);
                    }
                    if (actual <= 0) return new TailResult(true, reset, List.of(), "");
                    if (actual < bytes.length) bytes = Arrays.copyOf(bytes, actual);
                    lastNewline = -1;
                    lines = 0;
                    for (int i = 0; i < bytes.length; i++) {
                        if (bytes[i] == '\n') {
                            lines++;
                            lastNewline = i;
                            if (maxLines > 0 && lines >= maxLines) break;
                        }
                    }
                    if (lastNewline >= 0 || requested >= remaining || maxBytes <= 0) break;
                    requested = Math.min(remaining, Math.max(requested + 1L, requested * 2L));
                }
                if (lastNewline < 0) return new TailResult(true, reset, List.of(), "");
                String payload = new String(bytes, 0, lastNewline + 1, StandardCharsets.UTF_8);
                offset += lastNewline + 1L;
                List<Map<String, Object>> events = new ArrayList<>();
                for (String line : payload.split("\\R")) {
                    if (line == null || line.isBlank()) {
                        continue;
                    }
                    try {
                        Object parsed = MiniJson.parse(line);
                        Map<String, Object> event = MiniJson.object(parsed);
                        if (!event.isEmpty()) {
                            events.add(event);
                        }
                    } catch (RuntimeException ignored) {
                        // A telemetry line can be half-written while MT5/Python appends.
                        // It will be retried only if it has a newline on a later read.
                    }
                }
                return new TailResult(true, reset, events, "");
            } catch (IOException exc) {
                return new TailResult(false, false, List.of(), exc.getMessage() == null ? exc.toString() : exc.getMessage());
            }
        }

        record TailResult(boolean exists, boolean resetDetected, List<Map<String, Object>> events, String error) {
        }
    }

