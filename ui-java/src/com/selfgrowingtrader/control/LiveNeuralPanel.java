        private void applyActivity(Map<String, Object> container) {
            Map<String, Object> activity = objectAt(container, "activity");
            if (activity.isEmpty() && (container.containsKey("nodes") || container.containsKey("edges"))) {
                activity = container;
            }
            if (activity.isEmpty()) {
                return;
            }
            activeNodes.clear();
            activeEdges.clear();
            activeNodeData.clear();
            activeEdgeData.clear();
            for (Object item : MiniJson.array(activity.get("nodes"))) {
                Map<String, Object> data = MiniJson.object(item);
                String id = valueAt(data, "id", "");
                if (!id.isBlank()) {
                    activeNodes.add(id);
                    activeNodeData.put(id, data);
                }
            }
            for (Object item : MiniJson.array(activity.get("edges"))) {
                Map<String, Object> data = MiniJson.object(item);
                String id = valueAt(data, "id", "");
                if (!id.isBlank()) {
                    activeEdges.add(id);
                    activeEdgeData.put(id, data);
                }
            }
            activityRevision++;
        }

