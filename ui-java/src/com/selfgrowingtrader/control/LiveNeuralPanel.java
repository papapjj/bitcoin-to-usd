    private static Path resolveManifestPath(String raw, Path manifest, Path workspace, Path fallback) {
        String value = raw == null ? "" : raw.trim();
        if (value.isBlank()) return fallback == null ? null : normalizePath(fallback);
        // JSON is produced on Windows but inspection/build can occur elsewhere.
        // Normalize wire separators before Path parses the project-relative path.
        Path wire = Path.of(value.replace('\\', '/'));
        if (wire.isAbsolute()) return normalizePath(wire);
        List<Path> candidates = new ArrayList<>();
        if (workspace != null) candidates.add(workspace.resolve(wire));
        Path manifestDir = manifest == null ? null : manifest.toAbsolutePath().normalize().getParent();
        if (manifestDir != null) candidates.add(manifestDir.resolve(wire));
        if (manifestDir != null && manifestDir.getParent() != null) candidates.add(manifestDir.getParent().resolve(wire));
        for (Path candidate : candidates) {
            Path normalized = normalizePath(candidate);
            if (normalized != null && Files.isRegularFile(normalized)) return normalized;
        }
        return candidates.isEmpty() ? (fallback == null ? null : normalizePath(fallback)) : normalizePath(candidates.get(0));
    }

    private static Path resolveNewestRunScopedTelemetry(Path configured, Path workspace) {
        if (configured == null || configured.getFileName() == null) return null;
        Path root = workspace == null ? inferWorkspaceForRun(configured) : workspace;
        if (root == null) return null;
        Path runsDir = root.resolve("outputs").resolve("runs");
        if (!Files.isDirectory(runsDir)) return null;
        String fileName = configured.getFileName().toString();
        Path newest = null;
        long newestModified = Long.MIN_VALUE;
        try (var runDirs = Files.list(runsDir)) {
            for (Path runDir : runDirs.filter(Files::isDirectory).toList()) {
                Path candidate = runDir.resolve(fileName);
                if (!Files.isRegularFile(candidate)) continue;
                long modified = Files.getLastModifiedTime(candidate).toMillis();
                if (modified > newestModified) { newestModified = modified; newest = normalizePath(candidate); }
            }
        } catch (Exception ignored) { return null; }
        return newest;
    }

