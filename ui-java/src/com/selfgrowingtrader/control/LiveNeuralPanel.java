        private record ProjectedPoint(double x, double y, double depth, double perspective) {
            double distance(int px, int py) {
                return Math.hypot(x - px, y - py);
            }
        }

        private record NodeProjected(NodeData node, ProjectedPoint point) {
            double depth() {
                return point.depth();
            }
        }

        private record EdgeProjected(EdgeData edge, ProjectedPoint source, ProjectedPoint target) {
            double depth() {
                return (source.depth() + target.depth()) * 0.5;
            }
        }
