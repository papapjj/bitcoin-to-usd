        private static String formatVec(Vec3 point) {
            return "(" + formatNumber(point.x(), 3) + ", " + formatNumber(point.y(), 3) + ", " + formatNumber(point.z(), 3) + ")";
        }

        private static double pointToSegmentDistance(double px, double py, double ax, double ay, double bx, double by) {
            double dx = bx - ax;
            double dy = by - ay;
            if (dx == 0.0 && dy == 0.0) {
                return Math.hypot(px - ax, py - ay);
            }
            double t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy);
            t = Math.max(0.0, Math.min(1.0, t));
            double cx = ax + t * dx;
            double cy = ay + t * dy;
            return Math.hypot(px - cx, py - cy);
        }

        private static double clamp(double value, double low, double high) {
            return Math.max(low, Math.min(high, value));
        }

        private static double normalizeAngle(double radians) {
            double full = Math.PI * 2.0;
            double normalized = radians % full;
            return normalized < 0.0 ? normalized + full : normalized;
        }

