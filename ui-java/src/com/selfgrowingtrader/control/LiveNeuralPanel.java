    private void pollAsync() {
        if (!viewRunning || polling) {
            return;
        }
        polling = true;
        Path configuredEventPath = eventPathSupplier.get();
        ResolvedRunPaths resolved = resolveRunPaths(
                configuredEventPath,
                decisionProfilePathSupplier.get(),
                structuralEventPathSupplier.get(),
                networkDevelopmentPathSupplier.get()
        );
        Path path = resolved.eventPath();
        if (snapshot.eventCount == 0) {
            statusLabel.setText("Đang tải dần telemetry đầy đủ, không cắt dữ liệu: " + describeResolvedRun(resolved));
        }
        new SwingWorker<PollResult, Void>() {
            @Override
            protected PollResult doInBackground() {
                LiveEventTailer.TailResult events = tailer.read(path, UI_UNLIMITED, UI_INGEST_BYTES_PER_POLL);
                Path sidecarPath = resolveActionMetadataPath(path);
                LiveEventTailer.TailResult sidecar = sidecarPath == null
                        ? new LiveEventTailer.TailResult(false, false, List.of(), "")
                        : sidecarTailer.read(sidecarPath, UI_UNLIMITED, UI_INGEST_BYTES_PER_POLL);
                Path executionPath = resolveRuntimeFilePath(path, "self_growing_execution.csv");
                Map<String, Object> execution = readLatestTsvRow(executionPath);
                Path decisionProfilePath = resolved.decisionProfilePath();
                LiveEventTailer.TailResult decisionProfiles = decisionProfileTailer.read(
                        decisionProfilePath, UI_UNLIMITED, UI_INGEST_BYTES_PER_POLL);
                Path structuralEventPath = resolved.structuralEventPath();
                LiveEventTailer.TailResult structuralEvents = structuralEventTailer.read(
                        structuralEventPath, UI_UNLIMITED, UI_INGEST_BYTES_PER_POLL);
                Path networkDevelopmentPath = resolved.networkDevelopmentPath();
                LiveEventTailer.TailResult networkDevelopment = networkDevelopmentTailer.read(
                        networkDevelopmentPath, UI_UNLIMITED, UI_INGEST_BYTES_PER_POLL);
                return new PollResult(
                        events, sidecar, sidecarPath, execution, executionPath,
                        decisionProfiles, decisionProfilePath, structuralEvents, structuralEventPath,
                        networkDevelopment, networkDevelopmentPath, resolved
                );
            }

            @Override
            protected void done() {
                polling = false;
                if (!viewRunning) {
                    return;
                }
                try {
                    PollResult poll = get();
                    LiveEventTailer.TailResult result = poll.events();
                    if (result.resetDetected()) {
                        snapshot.reset();
                    }
                    for (Map<String, Object> event : result.events()) {
                        snapshot.apply(event);
                    }
                    if (poll.sidecar().resetDetected()) {
                        snapshot.clearSidecarProvenance();
                    }
                    for (Map<String, Object> item : poll.sidecar().events()) {
                        snapshot.applyActionMetadata(item, poll.sidecarPath());
                    }
                    snapshot.applyExecutionLedgerRow(poll.execution(), poll.executionPath());
                    if (poll.decisionProfiles().resetDetected()) {
                        snapshot.clearDecisionProfiles();
                    }
                    for (Map<String, Object> item : poll.decisionProfiles().events()) {
                        snapshot.applyDecisionProfile(item, poll.decisionProfilePath());
                    }
                    if (poll.structuralEvents().resetDetected()) {
                        snapshot.clearStructuralEvents();
                    }
                    for (Map<String, Object> item : poll.structuralEvents().events()) {
                        snapshot.applyStructuralEvent(item, poll.structuralEventPath());
                    }
                    if (poll.networkDevelopment().resetDetected()) {
                        snapshot.clearNetworkDevelopment();
                    }
                    for (Map<String, Object> item : poll.networkDevelopment().events()) {
                        snapshot.applyNetworkDevelopment(item, poll.networkDevelopmentPath());
                    }
                    if (!result.error().isBlank()) {
                        statusLabel.setText("Không thể đọc telemetry: " + result.error());
                    } else if (!result.exists()) {
                        statusLabel.setText("Chưa có telemetry tại nguồn đã resolve: " + describeResolvedRun(poll.resolved()) + " — hãy bật “Ghi telemetry khi train”.");
                    } else if (snapshot.eventCount == 0) {
                        statusLabel.setText("Đang chờ event đầu tiên: " + describeResolvedRun(poll.resolved()));
                    } else {
                        String sidecarText = snapshot.sidecarStatusText().isBlank()
                                ? ""
                                : " · sidecar " + snapshot.sidecarStatusText();
                        String explainabilityText = snapshot.explainabilityStatusText().isBlank()
                                ? ""
                                : " · " + snapshot.explainabilityStatusText();
                        statusLabel.setText(describeResolvedRun(poll.resolved()) + " · " + snapshot.eventCount + " event · cập nhật " + snapshot.lastEventTime
                                + sidecarText + explainabilityText);
                    }
                    if (!paused) {
                        updateUi();
                    }
                } catch (Exception exc) {
                    statusLabel.setText("Lỗi telemetry: " + exc.getMessage());
                    logSink.accept("[Live] telemetry read error: " + exc + "\n");
                }
            }
        }.execute();
    }

    /**
     * V190 resolver: mọi luồng telemetry phải đi qua active_run.json của
     * workspace. Không ghép relative path với outputs hai lần, không fallback
     * âm thầm sang log V9. Nếu manifest hỏng, mới quét run-scoped mới nhất.
     */
    private static ResolvedRunPaths resolveRunPaths(
            Path configuredEvent,
            Path configuredDecision,
            Path configuredStructural,
            Path configuredDevelopment
    ) {
        Path eventFallback = configuredEvent == null ? null : configuredEvent.toAbsolutePath().normalize();
        Path workspace = inferWorkspaceForRun(eventFallback);
        List<Path> manifests = activeRunCandidates(eventFallback, workspace);
        for (Path manifest : manifests) {
            if (manifest == null || !Files.isRegularFile(manifest)) continue;
            try {
                Map<String, Object> payload = MiniJson.object(MiniJson.parse(Files.readString(manifest, StandardCharsets.UTF_8)));
                Path event = resolveManifestPath(MiniJson.text(payload.get("event_path"), ""), manifest, workspace, eventFallback);
                if (event == null) continue;
                Path decision = resolveManifestPath(MiniJson.text(payload.get("decision_profile_path"), ""), manifest, workspace, null);
                Path structural = resolveManifestPath(MiniJson.text(payload.get("structural_event_path"), ""), manifest, workspace, null);
                Path development = resolveManifestPath(MiniJson.text(payload.get("network_development_path"), ""), manifest, workspace, null);
                if (decision == null) decision = derivedTelemetryPath(event, ".ho_so_quyet_dinh.jsonl");
                if (structural == null) structural = derivedTelemetryPath(event, ".phat_trien_cau_truc.jsonl");
                if (development == null) development = derivedTelemetryPath(event, ".theo_doi_phat_trien_mang.jsonl");
                return new ResolvedRunPaths(
                        normalizePath(event), normalizePath(decision), normalizePath(structural), normalizePath(development),
                        MiniJson.text(payload.get("root_run_id"), ""), "active_run.json", normalizePath(manifest)
                );
            } catch (Exception ignored) {
                // Try every candidate then use run scan; renderer remains read-only.
            }
        }
        Path event = resolveNewestRunScopedTelemetry(eventFallback, workspace);
        if (event == null) event = eventFallback;
        Path decision = chooseConfiguredOrDerived(configuredDecision, event, ".ho_so_quyet_dinh.jsonl");
        Path structural = chooseConfiguredOrDerived(configuredStructural, event, ".phat_trien_cau_truc.jsonl");
        Path development = chooseConfiguredOrDerived(configuredDevelopment, event, ".theo_doi_phat_trien_mang.jsonl");
        return new ResolvedRunPaths(normalizePath(event), normalizePath(decision), normalizePath(structural), normalizePath(development), "", "run-scan/fallback", null);
    }

