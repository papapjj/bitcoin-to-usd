        private void selectAt(int x, int y) {
            if (snapshot == null) {
                return;
            }
            NodeData nearestNode = null;
            double nearestDistance = Double.MAX_VALUE;
            for (NodeData node : renderNodes) {
                ProjectedPoint point = screenPositions.get(node.id());
                if (point == null) {
                    continue;
                }
                double distance = point.distance(x, y);
                if (distance < nearestDistance) {
                    nearestDistance = distance;
                    nearestNode = node;
                }
            }
            if (nearestNode != null && nearestDistance <= 19.0) {
                setFocusedNode(nearestNode.id());
                selectionConsumer.accept(nodeDetail(nearestNode));
                nodeSelectionConsumer.accept(nearestNode.id());
                return;
            }
            EdgeData nearestEdge = null;
            double edgeDistance = 11.0;
            for (EdgeData edge : renderEdges) {
                ProjectedPoint source = screenPositions.get(edge.src());
                ProjectedPoint target = screenPositions.get(edge.dst());
                if (source == null || target == null) {
                    continue;
                }
                double distance = pointToSegmentDistance(x, y, source.x(), source.y(), target.x(), target.y());
                if (distance < edgeDistance) {
                    edgeDistance = distance;
                    nearestEdge = edge;
                }
            }
            if (nearestEdge != null) {
                selectionConsumer.accept(edgeDetail(nearestEdge));
                edgeSelectionConsumer.accept(nearestEdge.id());
            }
        }

