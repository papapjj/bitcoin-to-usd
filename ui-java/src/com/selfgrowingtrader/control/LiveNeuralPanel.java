        private void markRecentStructuralState(Map<String, Object> state) {
            if (state == null || state.isEmpty()) return;
            recentlyChangedNodes.clear();
            recentlyChangedEdges.clear();
            for (Object item : MiniJson.array(state.get("nodes"))) {
                markQualifiedId(recentlyChangedNodes, valueAt(MiniJson.object(item), "id", ""), true);
            }
            for (Object item : MiniJson.array(state.get("edges"))) {
                markQualifiedId(recentlyChangedEdges, valueAt(MiniJson.object(item), "id", ""), false);
            }
            for (Object item : MiniJson.array(state.get("removed_node_ids"))) {
                markQualifiedId(recentlyChangedNodes, String.valueOf(item), true);
            }
            for (Object item : MiniJson.array(state.get("removed_edge_ids"))) {
                markQualifiedId(recentlyChangedEdges, String.valueOf(item), false);
            }
        }

        private void markRecentStructuralEvent(Map<String, Object> event) {
            if (event == null || event.isEmpty()) return;
            Map<String, Object> payload = objectAt(event, "su_kien");
            if (payload.isEmpty()) payload = event;
            for (Object item : MiniJson.array(payload.get("neuron_duoc_tao"))) {
                Map<String, Object> node = MiniJson.object(item);
                markQualifiedId(recentlyChangedNodes, valueAt(node, "id", String.valueOf(item)), true);
            }
            for (Object item : MiniJson.array(payload.get("lien_ket_duoc_tao"))) {
                Map<String, Object> edge = MiniJson.object(item);
                markQualifiedId(recentlyChangedEdges, valueAt(edge, "id", String.valueOf(item)), false);
            }
            String action = valueAt(payload, "hanh_dong", "").toLowerCase(Locale.ROOT);
            String target = valueAt(payload, "target", "");
            if (!target.isBlank()) {
                if (action.contains("neuron") || action.contains("node")) markQualifiedId(recentlyChangedNodes, target, true);
                if (action.contains("edge") || action.contains("lien_ket")) markQualifiedId(recentlyChangedEdges, target, false);
            }
        }

        private void markQualifiedId(Set<String> destination, String rawId, boolean node) {
            if (rawId == null || rawId.isBlank()) return;
            Map<String, ?> haystack = node ? nodes : edges;
            if (haystack.containsKey(rawId)) {
                destination.add(rawId);
                return;
            }
            for (String candidate : haystack.keySet()) {
                if (sameQualifiedId(candidate, rawId)) {
                    destination.add(candidate);
                    return;
                }
            }
        }

