        private static boolean sameQualifiedId(String left, String right) {
            if (left == null || right == null || left.isBlank() || right.isBlank()) {
                return false;
            }
            return left.equals(right) || left.endsWith("::" + right) || right.endsWith("::" + left);
        }

        void apply(Map<String, Object> event) {
            String type = valueAt(event, "event_type", "unknown");
            Map<String, Object> payload = objectAt(event, "payload");
            latest.put(type, event);
            eventCount++;
            lastEventTime = formatTime(MiniJson.number(event.get("created_at"), Double.NaN));

            if ("topology".equals(type)) {
                Map<String, Object> topology = objectAt(payload, "topology");
                replaceTopology(topology);
            }
            // Topology is intentionally structural-only.  Synapse state deltas
            // keep this exact in-memory graph current when plasticity changes
            // weights, gates, utility, fade, or lifecycle without creating a
            // new node/edge.
            applySynapseState(payload);
            if ("decision".equals(type)) {
                applyDecision(payload);
            }
            if ("feedback".equals(type) || "development".equals(type) || "lifecycle".equals(type)) {
                applyActivity(payload);
            }
            appendTimeline(type, event, payload);
        }

        private void replaceTopology(Map<String, Object> topology) {
            if (topology.isEmpty()) {
                return;
            }
            nodes.clear();
            edges.clear();
            for (Object item : MiniJson.array(topology.get("nodes"))) {
                Map<String, Object> node = MiniJson.object(item);
                String id = valueAt(node, "id", "");
                if (!id.isBlank()) {
                    nodes.put(id, NodeData.from(node));
                }
            }
            for (Object item : MiniJson.array(topology.get("edges"))) {
                Map<String, Object> edge = MiniJson.object(item);
                String id = valueAt(edge, "id", "");
                if (!id.isBlank()) {
                    edges.put(id, EdgeData.from(edge));
                }
            }
            reportedNodeCount = Math.max(nodes.size(), MiniJson.integer(topology.get("node_count"), nodes.size()));
            reportedEdgeCount = Math.max(edges.size(), MiniJson.integer(topology.get("edge_count"), edges.size()));
            topologyTruncated = reportedNodeCount > nodes.size() || reportedEdgeCount > edges.size();
            topologyRevision++;
            stateRevision++;
        }

        private void applySynapseState(Map<String, Object> payload) {
            Map<String, Object> delta = objectAt(payload, "synapse_state");
            if (delta.isEmpty()) {
                return;
            }
            boolean changed = false;
            boolean structural = false;
            for (Object item : MiniJson.array(delta.get("removed_node_ids"))) {
                String id = String.valueOf(item);
                if (nodes.remove(id) != null) {
                    changed = true;
                    structural = true;
                }
                activeNodes.remove(id);
                activeNodeData.remove(id);
            }
            for (Object item : MiniJson.array(delta.get("removed_edge_ids"))) {
                String id = String.valueOf(item);
                if (edges.remove(id) != null) {
                    changed = true;
                    structural = true;
                }
                activeEdges.remove(id);
                activeEdgeData.remove(id);
            }
            for (Object item : MiniJson.array(delta.get("nodes"))) {
                Map<String, Object> patch = MiniJson.object(item);
                String id = valueAt(patch, "id", "");
                if (id.isBlank()) {
                    continue;
                }
                NodeData current = nodes.get(id);
                Map<String, Object> merged = new LinkedHashMap<>();
                if (current != null) {
                    merged.putAll(current.raw());
                }
                merged.putAll(patch);
                nodes.put(id, NodeData.from(merged));
                changed = true;
                structural |= current == null || Boolean.TRUE.equals(patch.get("created"));
            }
            for (Object item : MiniJson.array(delta.get("edges"))) {
                Map<String, Object> patch = MiniJson.object(item);
                String id = valueAt(patch, "id", "");
                if (id.isBlank()) {
                    continue;
                }
                EdgeData current = edges.get(id);
                Map<String, Object> merged = new LinkedHashMap<>();
                if (current != null) {
                    merged.putAll(current.raw());
                }
                merged.putAll(patch);
                edges.put(id, EdgeData.from(merged));
                changed = true;
                structural |= current == null || Boolean.TRUE.equals(patch.get("created"));
            }
            if (changed) {
                stateRevision++;
            }
            if (structural) {
                topologyRevision++;
            }
        }

