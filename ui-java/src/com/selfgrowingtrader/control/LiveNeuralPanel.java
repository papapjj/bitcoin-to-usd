    private Path resolveRuntimeFilePath(Path eventPath, String fileName) {
        Path normalized = eventPath == null ? null : eventPath.toAbsolutePath().normalize();
        List<Path> candidates = new ArrayList<>();
        if (normalized != null && normalized.getParent() != null) {
            candidates.add(normalized.getParent().resolve(fileName));
        }
        Path workspace = inferWorkspaceRoot(normalized);
        if (workspace != null) {
            for (String runner : List.of("mt5_v2_runner_current", "mt5_v2_runner", "mt5_v2_runner_world")) {
                Path root = workspace.resolve(runner);
                candidates.add(root.resolve("MQL5").resolve("Files").resolve(fileName));
                candidates.add(root.resolve("Common").resolve("Files").resolve(fileName));
                Path tester = root.resolve("Tester");
                if (Files.isDirectory(tester)) {
                    try (var stream = Files.list(tester)) {
                        stream.filter(Files::isDirectory)
                                .filter(path -> path.getFileName() != null
                                        && path.getFileName().toString().startsWith("Agent-"))
                                .forEach(agent -> candidates.add(agent.resolve("MQL5").resolve("Files")
                                        .resolve(fileName)));
                    } catch (IOException ignored) {
                        // Read-only best effort; telemetry remains usable without MT5 files.
                    }
                }
            }
        }
        Path best = null;
        long bestModified = Long.MIN_VALUE;
        for (Path candidate : candidates) {
            try {
                if (candidate != null && Files.isRegularFile(candidate)) {
                    long modified = Files.getLastModifiedTime(candidate).toMillis();
                    if (modified > bestModified) {
                        best = candidate;
                        bestModified = modified;
                    }
                }
            } catch (IOException ignored) {
                // Ignore files being rotated by MT5/Python.
            }
        }
        return best;
    }

    private static Map<String, Object> readLatestTsvRow(Path path) {
        if (path == null || !Files.isRegularFile(path)) {
            return Map.of();
        }
        try {
            List<String> lines = Files.readAllLines(path, StandardCharsets.UTF_8);
            if (lines.size() < 2) {
                return Map.of();
            }
            String header = lines.get(0);
            String row = "";
            for (int i = lines.size() - 1; i >= 1; i--) {
                String candidate = lines.get(i);
                if (candidate != null && !candidate.isBlank()) {
                    row = candidate;
                    break;
                }
            }
            if (row.isBlank()) {
                return Map.of();
            }
            String[] columns = header.split("\\t", -1);
            String[] values = row.split("\\t", -1);
            LinkedHashMap<String, Object> parsed = new LinkedHashMap<>();
            for (int i = 0; i < columns.length && i < values.length; i++) {
                parsed.put(columns[i], values[i]);
            }
            return parsed;
        } catch (IOException exc) {
            return Map.of();
        }
    }

