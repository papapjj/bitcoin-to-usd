        private List<EdgeData> edgesFor(String nodeId, boolean incoming) {
            List<EdgeData> result = new ArrayList<>();
            for (EdgeData edge : snapshot.edges.values()) {
                if (incoming ? nodeId.equals(edge.dst()) : nodeId.equals(edge.src())) {
                    result.add(edge);
                }
            }
            result.sort(Comparator
                    .comparing((EdgeData edge) -> !snapshot.activeEdges.contains(edge.id()))
                    .thenComparing((EdgeData edge) -> -Math.abs(MiniJson.number(snapshot.activeEdgeData
                            .getOrDefault(edge.id(), Map.of()).get("contribution"), 0.0)))
                    .thenComparing((EdgeData edge) -> -Math.abs(edge.weight()))
                    .thenComparing(EdgeData::id));
            return result;
        }

        private int countActive(List<EdgeData> edges) {
            int total = 0;
            for (EdgeData edge : edges) {
                if (snapshot.activeEdges.contains(edge.id())) {
                    total++;
                }
            }
            return total;
        }

        private double sumActiveContribution(List<EdgeData> edges) {
            double total = 0.0;
            for (EdgeData edge : edges) {
                Map<String, Object> activity = snapshot.activeEdgeData.getOrDefault(edge.id(), Map.of());
                total += Math.abs(MiniJson.number(activity.get("contribution"), 0.0));
            }
            return total;
        }

        private static double sumAbsWeights(List<EdgeData> edges) {
            double total = 0.0;
            for (EdgeData edge : edges) {
                total += Math.abs(edge.weight());
            }
            return total;
        }

        private void appendEdgeList(StringBuilder out, String title, List<EdgeData> edges, boolean incoming) {
            out.append('\n').append(title).append(":\n");
            if (edges.isEmpty()) {
                out.append("  —\n");
                return;
            }
            int limit = edges.size();
            for (int i = 0; i < limit; i++) {
                EdgeData edge = edges.get(i);
                Map<String, Object> activity = snapshot.activeEdgeData.getOrDefault(edge.id(), Map.of());
                String peer = incoming ? edge.src() : edge.dst();
                out.append("  ").append(i + 1).append(". ")
                        .append(snapshot.activeEdges.contains(edge.id()) ? "* " : "  ")
                        .append(peer).append(" [").append(edge.kind()).append("]")
                        .append(" w=").append(formatNumber(edge.weight(), 4))
                        .append(" g=").append(formatNumber(MiniJson.number(activity.get("gate"), edge.gate()), 3))
                        .append(" c=").append(formatNumber(MiniJson.number(activity.get("contribution"), 0.0), 4))
                        .append(" · ").append(edge.id()).append('\n');
            }
        }

        private String rowLabel(NodeData node, boolean active) {
            String marker = snapshot.isRecentlyChangedNode(node.id()) ? "+" : (snapshot.isDecisionResponsible(node.id()) ? "!" : (active ? "*" : " "));
            Map<String, Object> runtime = snapshot.activeNodeData.getOrDefault(node.id(), Map.of());
            double raw = MiniJson.number(runtime.get("raw_input"), 0.0);
            double activation = MiniJson.number(runtime.get("activation"), 0.0);
            return String.format(Locale.ROOT, "%s %-9s %-12s %-14s raw=% .3f a=% .3f u=% .3f", marker,
                    blankAsDash(node.region()), blankAsDash(node.module()), blankAsDash(MiniJson.text(node.raw().get("local_id"), node.id())),
                    raw, activation, node.utility());
        }

        private static boolean containsAny(String value, String... needles) {
            String source = value == null ? "" : value.toLowerCase(Locale.ROOT);
            for (String needle : needles) {
                if (source.contains(needle)) {
                    return true;
                }
            }
            return false;
        }

        private static String truncate(String value, int limit) {
            String text = value == null || value.isBlank() ? "—" : value;
            return text.length() <= limit ? text : text.substring(0, Math.max(1, limit - 1)) + "…";
        }

        private static String blankAsDash(String value) {
            return value == null || value.isBlank() ? "—" : value;
        }

        private static void section(StringBuilder out, String title) {
            out.append(title).append('\n');
            out.append("-".repeat(Math.max(8, title.length()))).append('\n');
        }

        private static void kv(StringBuilder out, String label, Object value) {
            out.append(String.format(Locale.ROOT, "%-22s %s%n", label + ":", value == null ? "—" : value));
        }

        private static String compactMapForInspector(Map<String, Object> values, int limit) {
            if (values == null || values.isEmpty()) {
                return "—";
            }
            List<String> parts = new ArrayList<>();
            int count = 0;
            for (Map.Entry<String, Object> entry : values.entrySet()) {
                if (limit > 0 && count++ >= limit) {
                    parts.add("…");
                    break;
                }
                Object value = entry.getValue();
                if (value instanceof Number number) {
                    parts.add(entry.getKey() + "=" + formatNumber(number.doubleValue(), 4));
                } else {
                    parts.add(entry.getKey() + "=" + String.valueOf(value));
                }
            }
            return String.join(" · ", parts);
        }

        private static void appendRawFields(StringBuilder out, Map<String, Object> raw, int limit) {
            if (raw == null || raw.isEmpty()) {
                out.append("—\n");
                return;
            }
            int count = 0;
            for (Map.Entry<String, Object> entry : raw.entrySet()) {
                if (limit > 0 && count++ >= limit) {
                    out.append("…\n");
                    break;
                }
                Object value = entry.getValue();
                if (value instanceof List<?> list) {
                    out.append(entry.getKey()).append(": [").append(list.size()).append(" values]\n");
                } else if (value instanceof Map<?, ?> map) {
                    out.append(entry.getKey()).append(": {").append(map.size()).append(" fields}\n");
                } else {
                    out.append(entry.getKey()).append(": ").append(value).append('\n');
                }
            }
        }

