        NeuralGraphCanvas(Consumer<String> selectionConsumer) {
            this.selectionConsumer = selectionConsumer;
            setToolTipText("3D thật từ telemetry. Kéo trái để xoay · chuột phải để pan · lăn để zoom · click để inspect.");
            setCursor(Cursor.getPredefinedCursor(Cursor.CROSSHAIR_CURSOR));
            setFocusable(true);
            rotationTimer = new Timer(33, _event -> {
                if (autoRotate && isShowing()) {
                    yaw = normalizeAngle(yaw + 0.0085);
                    repaint();
                }
            });
            rotationTimer.setCoalesce(true);
            MouseAdapter mouse = new MouseAdapter() {
                @Override
                public void mousePressed(MouseEvent event) {
                    requestFocusInWindow();
                    dragButton = event.getButton();
                    lastMouseX = event.getX();
                    lastMouseY = event.getY();
                    dragMoved = false;
                }

                @Override
                public void mouseDragged(MouseEvent event) {
                    int dx = event.getX() - lastMouseX;
                    int dy = event.getY() - lastMouseY;
                    if (Math.abs(dx) + Math.abs(dy) > 1) {
                        dragMoved = true;
                    }
                    if (dragButton == MouseEvent.BUTTON1) {
                        yaw = normalizeAngle(yaw + dx * 0.0105);
                        pitch = clamp(pitch + dy * 0.0095, Math.toRadians(-78.0), Math.toRadians(78.0));
                    } else if (dragButton == MouseEvent.BUTTON2 || dragButton == MouseEvent.BUTTON3) {
                        panX += dx;
                        panY += dy;
                    }
                    lastMouseX = event.getX();
                    lastMouseY = event.getY();
                    repaint();
                }

                @Override
                public void mouseReleased(MouseEvent event) {
                    dragButton = MouseEvent.NOBUTTON;
                }

                @Override
                public void mouseClicked(MouseEvent event) {
                    if (!dragMoved && event.getButton() == MouseEvent.BUTTON1) {
                        selectAt(event.getX(), event.getY());
                    }
                }
            };
            addMouseListener(mouse);
            addMouseMotionListener(mouse);
            addMouseWheelListener(this::zoomAt);
        }

        void setSnapshot(LiveSnapshot snapshot) {
            this.snapshot = snapshot;
            if (snapshot != null && !focusedNodeId.isBlank() && !snapshot.nodes.containsKey(focusedNodeId)) {
                focusedNodeId = "";
                focusedEdgeIds = List.of();
                staticSelectionDirty = true;
            }
            int topologyRevision = snapshot == null ? Integer.MIN_VALUE : snapshot.topologyRevision;
            int activityRevision = snapshot == null ? Integer.MIN_VALUE : snapshot.activityRevision;
            boolean topologyChanged = staticSelectionDirty || topologyRevision != lastTopologyRevision;
            if (topologyChanged) {
                rebuildStaticSelection();
                lastTopologyRevision = topologyRevision;
                lastActivityRevision = Integer.MIN_VALUE;
            }
            if (topologyChanged || activityRevision != lastActivityRevision) {
                refreshDynamicRenderSet();
                lastActivityRevision = activityRevision;
            }
            repaint();
        }

