        private static String compactMap(Map<String, Object> values, int limit) {
            if (values.isEmpty()) {
                return "—";
            }
            List<String> out = new ArrayList<>();
            int count = 0;
            for (Map.Entry<String, Object> entry : values.entrySet()) {
                if (limit > 0 && count++ >= limit) {
                    out.add("…");
                    break;
                }
                Object value = entry.getValue();
                String text;
                if (value instanceof Number number) {
                    text = formatNumber(number.doubleValue(), 3);
                } else if (value instanceof List<?> list) {
                    text = compactList(MiniJson.array(list), UI_UNLIMITED);
                } else if (value instanceof Map<?, ?> map) {
                    text = "{" + MiniJson.object(map).size() + "}";
                } else {
                    text = String.valueOf(value);
                }
                out.add(entry.getKey() + "=" + text);
            }
            return String.join(" · ", out);
        }

        private static String compactList(List<Object> values, int limit) {
            if (values.isEmpty()) {
                return "—";
            }
            List<String> out = new ArrayList<>();
            int effectiveLimit = limit <= 0 ? Integer.MAX_VALUE : limit;
            for (int i = 0; i < values.size() && i < effectiveLimit; i++) {
                Object value = values.get(i);
                if (value instanceof Number number) {
                    out.add(formatNumber(number.doubleValue(), 3));
                } else if (value instanceof Map<?, ?> map) {
                    out.add("{" + MiniJson.object(map).size() + "}");
                } else if (value instanceof List<?> list) {
                    out.add("[" + MiniJson.array(list).size() + "]");
                } else {
                    out.add(String.valueOf(value));
                }
            }
            if (values.size() > effectiveLimit) {
                out.add("…");
            }
            return String.join(" · ", out);
        }

