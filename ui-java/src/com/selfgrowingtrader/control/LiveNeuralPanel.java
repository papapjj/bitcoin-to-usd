        private void rebuildList() {
            if (snapshot == null) {
                return;
            }
            String query = searchField.getText() == null ? "" : searchField.getText().trim().toLowerCase(Locale.ROOT);
            String filter = String.valueOf(filterBox.getSelectedItem());
            List<NodeData> nodes = new ArrayList<>(snapshot.nodes.values());
            nodes.removeIf(node -> !matches(node, query, filter));
            nodes.sort(Comparator
                    .comparing((NodeData node) -> !snapshot.isRecentlyChangedNode(node.id()))
                    .thenComparing((NodeData node) -> !snapshot.isDecisionResponsible(node.id()))
                    .thenComparing((NodeData node) -> !snapshot.activeNodes.contains(node.id()))
                    .thenComparing((NodeData node) -> -Math.abs(MiniJson.number(snapshot.activeNodeData
                            .getOrDefault(node.id(), Map.of()).get("activation"), 0.0)))
                    .thenComparing((NodeData node) -> -Math.abs(node.utility()))
                    .thenComparing(NodeData::region)
                    .thenComparing(NodeData::module)
                    .thenComparing(NodeData::id));
            syncing = true;
            try {
                nodeModel.clear();
                for (NodeData node : nodes) {
                    nodeModel.addElement(new NodeItem(node.id(), rowLabel(node, snapshot.activeNodes.contains(node.id()))));
                }
                if (!selectedNodeId.isBlank()) {
                    for (int i = 0; i < nodeModel.getSize(); i++) {
                        if (selectedNodeId.equals(nodeModel.get(i).id())) {
                            nodeList.setSelectedIndex(i);
                            nodeList.ensureIndexIsVisible(i);
                            break;
                        }
                    }
                }
            } finally {
                syncing = false;
            }
            int active = snapshot.activeNodes.size();
            int responsible = 0;
            for (NodeData node : snapshot.nodes.values()) {
                if (snapshot.isDecisionResponsible(node.id())) {
                    responsible++;
                }
            }
            summaryLabel.setText(snapshot.nodes.size() + " neuron · " + active + " active · " + responsible
                    + " chịu trách nhiệm · " + snapshot.recentlyChangedNodeCount() + " thay đổi gần nhất · hiển thị " + nodes.size()
                    + " · chọn node để focus toàn bộ liên kết vào/ra trong 3D");
            if (!selectedNodeId.isBlank() && snapshot.nodes.containsKey(selectedNodeId)) {
                showNode(selectedNodeId);
            }
        }

        private boolean matches(NodeData node, String query, String filter) {
            boolean active = snapshot.activeNodes.contains(node.id());
            boolean candidate = containsAny(node.lifecycle(), "candidate", "new", "born", "shadow")
                    || containsAny(String.valueOf(node.raw().get("created_by")), "growth", "micro", "birth");
            boolean fading = node.fade() < 0.98 || containsAny(node.lifecycle(), "fade", "prune", "disabled", "retired");
            if ("Chịu trách nhiệm quyết định".equals(filter) && !snapshot.isDecisionResponsible(node.id())) {
                return false;
            }
            if ("Chỉ neuron active".equals(filter) && !active) {
                return false;
            }
            if ("Có plasticity".equals(filter) && Math.abs(node.plasticity()) < 1e-9) {
                return false;
            }
            if ("Mới sinh / candidate".equals(filter) && !candidate) {
                return false;
            }
            if ("Thay đổi gần nhất".equals(filter) && !snapshot.isRecentlyChangedNode(node.id())) {
                return false;
            }
            if ("Đang fade / prune".equals(filter) && !fading) {
                return false;
            }
            if (query.isBlank()) {
                return true;
            }
            String haystack = (node.id() + " " + node.module() + " " + node.region() + " " + node.lifecycle()
                    + " " + node.moduleId() + " " + node.homeContextKey()).toLowerCase(Locale.ROOT);
            return haystack.contains(query);
        }

