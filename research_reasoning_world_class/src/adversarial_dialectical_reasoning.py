@dataclass
class DialecticalConfig:
    input_dim: int = 256
    hidden_dim: int = 256
    num_debate_turns: int = 3
    num_heads: int = 4
    dropout: float = 0.05
    prm_threshold: float = 0.88
    trap_similarity_threshold: float = 0.85
    max_latency_ms: float = 50.0


@dataclass
class DialecticalVerdict:
    action: int                     # -1: SELL, 0: HOLD, 1: BUY
    prm_score: float                # Logical consistency [0.0, 1.0]
    confidence: float               # Calibrated confidence [0.0, 1.0]
    is_counter_punch: bool          # True if action was generated by inverting an exposed trap
    trap_type: str                  # "NONE", "BULL_TRAP", "BEAR_TRAP", "MOMENTUM_CONFIRMED"
    proponent_conviction: float     # [0.0, 1.0]
    adversary_conviction: float     # [0.0, 1.0]
    debate_margin: float            # Proponent - Adversary in [-1.0, 1.0]
    latency_ms: float               # Execution time in ms
    debate_history: List[Dict[str, float]]
    was_backtracked: bool = False
    faulty_step: int = -1
    backtrack_magnitude: float = 0.0
    search_depth: int = 3


class ProponentThesisNetwork(nn.Module):
    """
    Proponent Network (Alpha Seeker).
    Formulates directional trading thesis based on market structure and order flow.
    """
    def __init__(self, hidden_dim: int = 256):
        super().__init__()
        self.encoder = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.LayerNorm(hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, hidden_dim)
        )
        self.thesis_head = nn.Linear(hidden_dim, hidden_dim)
        self.conviction_head = nn.Sequential(
            nn.Linear(hidden_dim, 64),
            nn.GELU(),
            nn.Linear(64, 2)  # [Long Conviction, Short Conviction]
        )

    def forward(self, state: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        features = self.encoder(state)
        thesis = torch.tanh(self.thesis_head(features))
        convictions = torch.sigmoid(self.conviction_head(features))
        return thesis, convictions


class AdversaryRedTeamNetwork(nn.Module):
    """
    Adversary Red-Team Network (Devil's Advocate & Trap Hunter).
    Actively hunts for liquidity sweeps, false breakouts, and institutional distribution traps.
    """
    def __init__(self, hidden_dim: int = 256):
        super().__init__()
        self.encoder = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.LayerNorm(hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, hidden_dim)
        )
        self.critique_head = nn.Linear(hidden_dim, hidden_dim)
        # Trap classification head: [No Trap, Bull Trap (Liquidity Sweep High), Bear Trap (Liquidity Sweep Low)]
        self.trap_detector = nn.Sequential(
            nn.Linear(hidden_dim * 2, 128),
            nn.GELU(),
            nn.Linear(128, 3)
        )
        self.stress_head = nn.Sequential(
            nn.Linear(hidden_dim, 64),
            nn.GELU(),
            nn.Linear(64, 1),
            nn.Sigmoid()
        )

    def forward(self, state: torch.Tensor, proponent_thesis: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        critique_feat = self.encoder(state)
        critique = torch.tanh(self.critique_head(critique_feat))
        
        # Cross-examine state + thesis for trap detection
        combined = torch.cat([critique_feat, proponent_thesis], dim=-1)
        trap_logits = self.trap_detector(combined)
        trap_probs = F.softmax(trap_logits, dim=-1)
        stress_level = self.stress_head(critique_feat).squeeze(-1)
        
        return critique, trap_probs, stress_level


class DialecticalCrossExamination(nn.Module):
    """
    Multi-Turn Dialectical Cross-Examination Layer with Adversarial Search & Backtracking.
    Allows Proponent and Adversary to search counter-scenarios and backtrack/revise hypotheses over T rounds.
    """
    def __init__(self, hidden_dim: int = 256, num_heads: int = 4):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.cross_attn = nn.MultiheadAttention(embed_dim=hidden_dim, num_heads=num_heads, batch_first=True)
        self.proponent_update = nn.GRUCell(hidden_dim, hidden_dim)
        self.adversary_update = nn.GRUCell(hidden_dim, hidden_dim)
        
        # Backtracking Revision Mechanism:
        # Reverses Proponent premise when Adversary produces severe contradictory counter-evidence
        self.contradiction_gate = nn.Sequential(
            nn.Linear(hidden_dim * 2, 64),
            nn.GELU(),
            nn.Linear(64, 1),
            nn.Sigmoid()
        )
        self.backtrack_revision = nn.Sequential(
            nn.Linear(hidden_dim * 2, hidden_dim),
            nn.Tanh()
        )
        self.backtrack_norm = nn.LayerNorm(hidden_dim)

    def forward(
        self,
        proponent_state: torch.Tensor,
        adversary_state: torch.Tensor,
        turns: int = 3
    ) -> Tuple[torch.Tensor, torch.Tensor, List[Dict[str, float]], bool, float, int]:
        B, D = proponent_state.size()
        p_h = proponent_state
        a_h = adversary_state
        history = []
        was_backtracked = False
        faulty_step = -1
        max_backtrack_mag = 0.0

        for t in range(turns):
            # Step 1: Adversary searches for thesis vulnerabilities
            seq_p = p_h.unsqueeze(1)
            seq_a = a_h.unsqueeze(1)
            
            # Cross attention: Proponent attends to Adversary attacks
            p_attacked, _ = self.cross_attn(seq_p, seq_a, seq_a)
            p_cand = self.proponent_update(p_attacked.squeeze(1), p_h)
            
            # Step 2: Contradiction Detection & Backtracking Revision
            joint = torch.cat([p_h, a_h], dim=-1)
            contra_score = self.contradiction_gate(joint).squeeze(-1)
            if contra_score.mean().item() >= 0.70:
                # Contradiction detected -> Backtrack & revise premise!
                delta = self.backtrack_revision(joint)
                p_revised = self.backtrack_norm((1.0 - 1.5 * contra_score.unsqueeze(-1)) * p_h - 0.5 * delta)
                mag = float(torch.norm(p_revised - p_h, dim=-1).mean().item())
                p_h = p_revised
                was_backtracked = True
                faulty_step = t
                max_backtrack_mag = max(max_backtrack_mag, mag)
            else:
                p_h = p_cand
            
            # Step 3: Adversary adapts to revised Proponent defense
            a_counter, _ = self.cross_attn(seq_a, seq_p, seq_p)
            a_h = self.adversary_update(a_counter.squeeze(1), a_h)
            
            p_norm = float(torch.norm(p_h, dim=-1).mean().item())
            a_norm = float(torch.norm(a_h, dim=-1).mean().item())
            history.append({
                "round": t + 1,
                "proponent_pressure": round(p_norm, 4),
                "adversary_pressure": round(a_norm, 4),
                "was_backtracked": was_backtracked,
                "faulty_step": faulty_step,
            })

        return p_h, a_h, history, was_backtracked, max_backtrack_mag, faulty_step


class MetacognitiveDialecticalArbiter(nn.Module):
    """
    Metacognitive Arbiter & Process Reward Model (PRM) Verifier.
    Adjudicates the debate with game-theoretic rigor.
    
    Decision Rules:
    1. If Proponent convincingly overcomes Red-Team attacks (PRM >= 0.88, Margin >= +0.20):
       -> Approves regular SNIPER entry.
    2. If Adversary Red-Team proves a high-probability Trap:
       -> EXPLOITS THE TRAP (COUNTER-PUNCH):
          * Bull Trap detected -> Generates SNIPER SELL (fade the fake breakout).
          * Bear Trap detected -> Generates SNIPER BUY (fade the fake breakdown / spring).
    3. In case of unresolved deadlock or high entropy:
       -> Enforces safe HOLD.
    """
    def __init__(self, hidden_dim: int = 256, prm_threshold: float = 0.35, trap_threshold: float = 0.60, action_prob_threshold: float = 0.35, margin_threshold: float = 0.55):
        super().__init__()
        self.prm_threshold = prm_threshold
        self.trap_threshold = trap_threshold
        self.action_prob_threshold = action_prob_threshold
        self.margin_threshold = margin_threshold
        self.arbiter_net = nn.Sequential(
            nn.Linear(hidden_dim * 2, hidden_dim),
            nn.LayerNorm(hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, 64),
            nn.GELU(),
            nn.Linear(64, 3) # [HOLD, BUY, SELL]
        )
        self.prm_evaluator = nn.Sequential(
            nn.Linear(hidden_dim * 2, 64),
            nn.GELU(),
            nn.Linear(64, 1),
            nn.Sigmoid()
        )

    def forward(
        self,
        final_proponent: torch.Tensor,
        final_adversary: torch.Tensor,
        trap_probs: torch.Tensor,
        proponent_convictions: torch.Tensor,
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """
        Returns:
            action: (B,) in {-1, 0, 1}
            prm_score: (B,) in [0.0, 1.0]
            confidence: (B,) in [0.0, 1.0]
            counter_punch_mask: (B,) boolean
        """
        B = final_proponent.size(0)
        synthesis = torch.cat([final_proponent, final_adversary], dim=-1)
        
        logits = self.arbiter_net(synthesis)
        probs = F.softmax(logits, dim=-1) # [HOLD (0), BUY (1), SELL (2)]
        prm_score = self.prm_evaluator(synthesis).squeeze(-1)
        
        # Trap Probabilities: [No Trap (0), Bull Trap (1), Bear Trap (2)]
        p_no_trap = trap_probs[:, 0]
        p_bull_trap = trap_probs[:, 1]
        p_bear_trap = trap_probs[:, 2]
        
        action = torch.zeros(B, dtype=torch.long, device=final_proponent.device)
        confidence = torch.zeros(B, dtype=torch.float32, device=final_proponent.device)
        counter_punch = torch.zeros(B, dtype=torch.bool, device=final_proponent.device)
        
        for i in range(B):
            b_trap = float(p_bull_trap[i].item())
            r_trap = float(p_bear_trap[i].item())
            cur_prm = float(prm_score[i].item())
            
            # CASE A: GENUINE TRAP EXPLOITATION (Counter-Punch)
            # Only trigger when Adversary detects institutional trap with high probability (>= 0.80)
            if b_trap >= self.trap_threshold and b_trap > r_trap + 0.15:
                # Bull Trap exposed -> Exploit by Shorting (SELL)!
                action[i] = -1
                confidence[i] = max(0.88, b_trap)
                prm_score[i] = max(float(prm_score[i].item()), float(confidence[i].item()))
                counter_punch[i] = True
            elif r_trap >= self.trap_threshold and r_trap > b_trap + 0.15:
                # Bear Trap exposed -> Exploit by Longing (BUY)!
                action[i] = 1
                confidence[i] = max(0.88, r_trap)
                prm_score[i] = max(float(prm_score[i].item()), float(confidence[i].item()))
                counter_punch[i] = True
                
            # CASE B: PROPONENT CONVICTION VERIFIED BY PRM (Regular Trend Expansion & Sniper Turns)
            elif cur_prm >= self.prm_threshold:
                act_prob_thresh = getattr(self, "action_prob_threshold", 0.35)
                p_buy = float(probs[i, 1].item())
                p_sell = float(probs[i, 2].item())
                p_hold = float(probs[i, 0].item())
                
                b_score = float(proponent_convictions[i, 0].item()) if proponent_convictions.size(-1) >= 2 else 0.5
                r_score = float(proponent_convictions[i, 1].item()) if proponent_convictions.size(-1) >= 2 else 0.5
                # Standardized Bilateral Z-Score Dialectical Margin (b_med=0.0362, b_iqr=0.0907; r_med=0.2358, r_iqr=0.0332)
                b_z = (b_score - 0.0362) / 0.0907
                r_z = (r_score - 0.2358) / 0.0332
                margin = b_z - r_z
                margin_threshold = getattr(self, "margin_threshold", 0.55)
                
                # Symmetrical pure dialectical conviction arbitration:
                # Bull victory: dialectical conviction margin >= threshold (0.07)
                if margin >= margin_threshold:
                    action[i] = 1
                    confidence[i] = max(p_buy, b_score)
                # Bear victory: dialectical conviction margin <= -threshold (-0.07)
                elif margin <= -margin_threshold:
                    action[i] = -1
                    confidence[i] = max(p_sell, r_score)
                else:
                    action[i] = 0
                    confidence[i] = p_hold
            else:
                # CASE C: AMBIGUOUS DEBATE -> ENFORCE SAFE HOLD
                action[i] = 0
                confidence[i] = 0.50

        return action, prm_score, confidence, counter_punch


class AdversarialDialecticalReasoningEngine(nn.Module):
    """
    Complete Frontier Adversarial Dialectical Reasoning Engine.
    Serves as the high-IQ metacognitive brain for Mythos Trading Architecture.
    """
    def __init__(self, config: Optional[DialecticalConfig] = None):
        super().__init__()
        self.config = config or DialecticalConfig()
        
        # State projection from ingress 233D / latent 768D to internal hidden_dim 256D
        self.input_proj = nn.Sequential(
            nn.Linear(self.config.input_dim, self.config.hidden_dim),
            nn.LayerNorm(self.config.hidden_dim),
            nn.GELU()
        )
        
        self.proponent = ProponentThesisNetwork(self.config.hidden_dim)
        self.adversary = AdversaryRedTeamNetwork(self.config.hidden_dim)
        self.cross_examination = DialecticalCrossExamination(self.config.hidden_dim, self.config.num_heads)
        self.arbiter = MetacognitiveDialecticalArbiter(self.config.hidden_dim, self.config.prm_threshold)

    def forward(self, market_state: torch.Tensor) -> DialecticalVerdict:
        t0 = time.perf_counter()
        if market_state.dim() == 1:
            market_state = market_state.unsqueeze(0)
            
        B, in_dim = market_state.size()
        if in_dim != self.config.input_dim:
            if hasattr(self, "_dynamic_proj") and self._dynamic_proj.in_features == in_dim:
                z = self._dynamic_proj(market_state)
            else:
                self._dynamic_proj = nn.Linear(in_dim, self.config.hidden_dim).to(market_state.device)
                z = self._dynamic_proj(market_state)
        else:
            z = self.input_proj(market_state)
            
        z = torch.nan_to_num(z, nan=0.0)
        
        # Step 1: Proponent formulates affirmative thesis
        thesis, convictions = self.proponent(z)
        
        # Step 2: Adversary red-teams the thesis, hunting for traps
        critique, trap_probs, stress_level = self.adversary(z, thesis)
        
        # Step 3: Multi-turn cross-examination debate with search & backtracking
        final_p, final_a, debate_history, was_backtracked, backtrack_mag, faulty_step = self.cross_examination(
            thesis, critique, turns=self.config.num_debate_turns
        )
        
        # Step 4: Metacognitive arbitration & trap exploitation
        actions, prm_scores, confidences, counter_punches = self.arbiter(
            final_p, final_a, trap_probs, convictions
        )
        
        latency_ms = (time.perf_counter() - t0) * 1000.0
        
        # Determine dominant trap type
        p_trap = trap_probs[0]
        if bool(counter_punches[0].item()):
            if int(actions[0].item()) == -1:
                trap_type = "BULL_TRAP"
            elif int(actions[0].item()) == 1:
                trap_type = "BEAR_TRAP"
            else:
                trap_type = "INDETERMINATE"
        elif float(p_trap[1].item()) >= 0.60:
            trap_type = "BULL_TRAP"
        elif float(p_trap[2].item()) >= 0.60:
            trap_type = "BEAR_TRAP"
        elif float(p_trap[0].item()) >= 0.70:
            trap_type = "NO_TRAP_CONFIRMED"
        else:
            trap_type = "INDETERMINATE"
            
        long_conv = float(convictions[0, 0].item())
        short_conv = float(convictions[0, 1].item())
        prop_c = max(long_conv, short_conv)
        adv_c = float(stress_level[0].item())
        margin = prop_c - adv_c

        return DialecticalVerdict(
            action=int(actions[0].item()),
            prm_score=float(prm_scores[0].item()),
            confidence=float(confidences[0].item()),
            is_counter_punch=bool(counter_punches[0].item()),
            trap_type=trap_type,
            proponent_conviction=prop_c,
            adversary_conviction=adv_c,
            debate_margin=margin,
            latency_ms=latency_ms,
            debate_history=debate_history,
            was_backtracked=was_backtracked,
            faulty_step=faulty_step,
            backtrack_magnitude=backtrack_mag,
            search_depth=self.config.num_debate_turns,
        )
