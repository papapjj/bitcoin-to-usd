class TestChallengerPart4SlicedWalkForwardIsolationOracle(unittest.TestCase):
    """
    Part 4 Oracle: Stress-tests temporal isolation of SlicedM1Environment,
    verifying zero lookahead beyond slice boundaries, coordinate remapping, and immutability.
    """

    @classmethod
    def setUpClass(cls):
        cls.master = EnvironmentFixture.get_env()
        cls.slice = SlicedM1Environment(cls.master, start_idx=1000, end_idx=5000, name="IsolationSlice")

    def test_4_1_zero_lookahead_at_terminal_slice_boundary(self):
        """
        Verifies that querying simulate_trade at terminal boundary (bar_idx = total_bars - 1)
        clamps max_holding_bars to 0 and NEVER accesses future data outside slice.
        """
        self.assertEqual(self.slice.total_bars, 4000)
        terminal_idx = self.slice.total_bars - 1

        res = self.slice.simulate_trade(terminal_idx, action=1, sl_atr=2.0, tp_atr=4.0, max_holding_bars=60)
        self.assertEqual(res.holding_bars, 0)
        self.assertEqual(res.exit_reason, "DATASET_END")
        self.assertEqual(res.exit_bar_idx, terminal_idx)

        # At near boundary (total_bars - 4)
        near_idx = self.slice.total_bars - 4
        res_near = self.slice.simulate_trade(near_idx, action=1, sl_atr=10.0, tp_atr=10.0, max_holding_bars=60)
        self.assertLessEqual(res_near.holding_bars, 3)
        self.assertLessEqual(res_near.exit_bar_idx, terminal_idx)

    def test_4_2_coordinate_space_remapping_oracle(self):
        """
        Verifies coordinate remapping:
        res_slice.exit_bar_idx == res_master.exit_bar_idx - start_idx.
        """
        res_slice = self.slice.simulate_trade(200, action=1, sl_atr=2.0, tp_atr=4.0)
        master_bar = self.slice.start_idx + 200
        res_master = self.master.simulate_trade(master_bar, action=1, sl_atr=2.0, tp_atr=4.0)

        self.assertEqual(res_slice.holding_bars, res_master.holding_bars)
        self.assertEqual(res_slice.exit_bar_idx, res_master.exit_bar_idx - self.slice.start_idx)
        self.assertGreaterEqual(res_slice.exit_bar_idx, 0)
        self.assertLess(res_slice.exit_bar_idx, self.slice.total_bars)

    def test_4_3_traderesult_frozen_immutability_oracle(self):
        """
        Verifies TradeResult is a frozen dataclass: direct mutation raises FrozenInstanceError,
        while dataclasses.replace creates an independent modified clone.
        """
        res = self.slice.simulate_trade(50, action=1, sl_atr=2.0, tp_atr=4.0)

        # Direct mutation must fail
        with self.assertRaises((FrozenInstanceError, AttributeError)):
            res.exit_bar_idx = 12345

        with self.assertRaises((FrozenInstanceError, AttributeError)):
            res.pnl_usd = 9999.0

        # dataclasses.replace creates a valid clone without modifying original
        res_clone = replace(res, pnl_usd=777.0)
        self.assertEqual(res_clone.pnl_usd, 777.0)
        self.assertNotEqual(res.pnl_usd, 777.0)


