# INDEPENDENT NAIVE SIMULATION ORACLE (Ground Truth Reference)
# ==============================================================================
def naive_ground_truth_simulate_trade(
    open_arr: np.ndarray,
    high_arr: np.ndarray,
    low_arr: np.ndarray,
    close_arr: np.ndarray,
    atr_arr: np.ndarray,
    bar_idx: int,
    total_bars: int,
    action: int,
    sl_atr: float,
    tp_atr: float,
    max_holding_bars: int = 60,
    spread_usd: float = 2.50,
) -> Dict[str, Any]:
    """
    Independent ground-truth trade simulation in pure Python iterating directly
    over raw price arrays without using RealM1Environment.simulate_trade.
    """
    if action not in (1, 2):
        raise ValueError(f"Invalid action {action}")
    if sl_atr <= 0 or tp_atr <= 0:
        raise ValueError("SL and TP must be positive")
    if bar_idx < 0 or bar_idx >= total_bars:
        raise IndexError(f"bar_idx {bar_idx} out of range")

    half_spread = spread_usd / 2.0
    atr = max(float(atr_arr[bar_idx]), 1e-4)
    ref_close = float(close_arr[bar_idx])

    avail = min(max_holding_bars, total_bars - 1 - bar_idx)
    if avail <= 0:
        entry_price = ref_close + half_spread if action == 1 else ref_close - half_spread
        exit_price = ref_close - half_spread if action == 1 else ref_close + half_spread
        pnl = (exit_price - entry_price) if action == 1 else (entry_price - exit_price)
        return {
            "pnl_usd": float(pnl),
            "return_atr": float(pnl / atr),
            "exit_type": "timestop",
            "holding_bars": 0,
            "exit_reason": "DATASET_END",
            "entry_price": float(entry_price),
            "exit_price": float(exit_price),
            "exit_bar_idx": bar_idx,
        }

    if action == 1:  # BUY
        entry_price = ref_close + half_spread
        sl_level = ref_close - (sl_atr * atr)
        tp_level = ref_close + (tp_atr * atr)

        hit_sl = False
        hit_tp = False
        exit_bar = None
        exit_reason = None
        exit_level = None
        exit_type = None

        for k in range(avail):
            idx = bar_idx + 1 + k
            o_k = float(open_arr[idx])
            h_k = float(high_arr[idx])
            l_k = float(low_arr[idx])

            sl_breach = l_k <= sl_level
            tp_breach = h_k >= tp_level

            if sl_breach and tp_breach:
                # Conservative simultaneous breach: SL has priority
                hit_sl = True
                exit_bar = k + 1
                exit_level = min(sl_level, o_k)
                exit_type = "sl"
                exit_reason = "SIMULTANEOUS_SL_FIRST"
                break
            elif sl_breach:
                hit_sl = True
                exit_bar = k + 1
                exit_level = min(sl_level, o_k)
                exit_type = "sl"
                exit_reason = "SL_HIT"
                break
            elif tp_breach:
                hit_tp = True
                exit_bar = k + 1
                exit_level = tp_level
                exit_type = "tp"
                exit_reason = "TP_HIT"
                break

        if not hit_sl and not hit_tp:
            exit_bar = avail
            c_last = float(close_arr[bar_idx + avail])
            exit_level = c_last
            exit_type = "timestop"
            exit_reason = "TIME_STOP"

        exit_price = exit_level - half_spread
        pnl = exit_price - entry_price

    else:  # SELL
        entry_price = ref_close - half_spread
        sl_level = ref_close + (sl_atr * atr)
        tp_level = ref_close - (tp_atr * atr)

        hit_sl = False
        hit_tp = False
        exit_bar = None
        exit_reason = None
        exit_level = None
        exit_type = None

        for k in range(avail):
            idx = bar_idx + 1 + k
            o_k = float(open_arr[idx])
            h_k = float(high_arr[idx])
            l_k = float(low_arr[idx])

            sl_breach = h_k >= sl_level
            tp_breach = l_k <= tp_level

            if sl_breach and tp_breach:
                # Conservative simultaneous breach: SL has priority
                hit_sl = True
                exit_bar = k + 1
                exit_level = max(sl_level, o_k)
                exit_type = "sl"
                exit_reason = "SIMULTANEOUS_SL_FIRST"
                break
            elif sl_breach:
                hit_sl = True
                exit_bar = k + 1
                exit_level = max(sl_level, o_k)
                exit_type = "sl"
                exit_reason = "SL_HIT"
                break
            elif tp_breach:
                hit_tp = True
                exit_bar = k + 1
                exit_level = tp_level
                exit_type = "tp"
                exit_reason = "TP_HIT"
                break

        if not hit_sl and not hit_tp:
            exit_bar = avail
            c_last = float(close_arr[bar_idx + avail])
            exit_level = c_last
            exit_type = "timestop"
            exit_reason = "TIME_STOP"

        exit_price = exit_level + half_spread
        pnl = entry_price - exit_price

    return {
        "pnl_usd": float(pnl),
        "return_atr": float(pnl / atr),
        "exit_type": exit_type,
        "holding_bars": int(exit_bar),
        "exit_reason": exit_reason,
        "entry_price": float(entry_price),
        "exit_price": float(exit_price),
        "exit_bar_idx": int(bar_idx + exit_bar),
    }


