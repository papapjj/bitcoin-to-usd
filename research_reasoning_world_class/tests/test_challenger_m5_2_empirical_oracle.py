class TestChallengerPart2WorldModelInvariantsOracle(unittest.TestCase):
    """
    Part 2 Oracle: Stress-tests World Model multi-step unrolling numerical stability,
    proves non-circularity sensitivity mathematically, and checks categorical bounds.
    """

    def setUp(self):
        self.wm = LatentDynamicsWorldModel(obs_dim=137, latent_dim=768, action_dim=64)

    def test_2_1_deep_25_step_unrolling_stability_oracle(self):
        """
        Unrolls state transition across 25 sequential recurrent steps:
        z_{k+1} = LayerNorm(z_k + 0.25 * g(z_k, a_k)).
        Verifies representation stability: finite activations, bounded L2 norm,
        and LayerNorm normalization at every step.
        """
        obs_137 = torch.randn(1, 137)
        z_curr = self.wm.encode_state(obs_137)

        self.assertEqual(z_curr.shape, (1, 768))
        self.assertTrue(torch.all(torch.isfinite(z_curr)))

        initial_norm = float(torch.norm(z_curr, p=2).item())

        for step in range(25):
            act_idx = (step % 3)
            act_vec = self.wm.encode_action(act_idx)
            z_curr = self.wm.transition(z_curr, act_vec)

            # Assert no NaNs or Infs
            self.assertTrue(torch.all(torch.isfinite(z_curr)), f"Non-finite at step {step}")

            # Verify LayerNorm property: mean ~= 0, std ~= 1
            mean_val = float(z_curr.mean().item())
            std_val = float(z_curr.std(unbiased=False).item())
            self.assertAlmostEqual(mean_val, 0.0, delta=0.15, msg=f"Mean diverged at step {step}")
            self.assertAlmostEqual(std_val, 1.0, delta=0.15, msg=f"Std diverged at step {step}")

            # Verify L2 norm is strictly controlled and does not explode
            curr_norm = float(torch.norm(z_curr, p=2).item())
            self.assertLess(curr_norm, 100.0, f"Norm exploded to {curr_norm} at step {step}")
            self.assertGreater(curr_norm, 1.0, f"Norm collapsed to {curr_norm} at step {step}")

    def test_2_2_non_circular_trajectory_target_sensitivity_oracle(self):
        """
        Mathematically proves non-circularity:
        1. Supervision targets MUST originate from future price paths s_{t+k}, NOT predictions.
        2. Perturbing future prices MUST alter the target trajectory (Delta target != 0).
        3. Perturbing model predictions MUST NOT alter the target trajectory (Delta target == 0).
        """
        env = EnvironmentFixture.get_env()
        start_idx = 1000
        actions = [1, 1, 2, 0, 1]

        # 1. Base targets from real environment
        s0, fut_obs_base, val_base, rew_base = generate_trajectory_targets(
            env=env, start_idx=start_idx, actions=actions, horizon_k=5, sl_atr=2.0, tp_atr=4.0
        )

        # 2. Perturb model unrolled prediction
        z0 = self.wm.encode_state(torch.from_numpy(s0).unsqueeze(0))
        act_tensor = torch.tensor([actions], dtype=torch.long)
        pred_z, pred_v, pred_r = self.wm.unroll_trajectory(z0, act_tensor)

        # Perturb predictions by massive factor
        pred_z_perturbed = pred_z + 1000.0
        pred_v_perturbed = pred_v + 50.0

        # Targets must remain completely independent of model predictions
        s0_rep, fut_obs_rep, val_rep, rew_rep = generate_trajectory_targets(
            env=env, start_idx=start_idx, actions=actions, horizon_k=5, sl_atr=2.0, tp_atr=4.0
        )
        np.testing.assert_array_equal(val_base, val_rep)
        np.testing.assert_array_equal(rew_base, rew_rep)
        np.testing.assert_array_equal(fut_obs_base, fut_obs_rep)

        # 3. Targets are derived from true environment observations:
        # Check that fut_obs matches env.get_observation(start_idx + k + 1)
        for k in range(5):
            expected_fut = env.get_observation(start_idx + k + 1)
            np.testing.assert_allclose(fut_obs_base[k], expected_fut, atol=1e-5)

    def test_2_3_probability_and_value_normalization_oracle(self):
        """
        Verifies mathematical normalization:
        - Value predictions strictly bounded in [-1.0, 1.0] via tanh.
        - MCTS policy visit distributions strictly sum to 1.0 (sum p_i == 1.0).
        """
        # Test value head bounds across 50 extreme inputs
        extreme_z = torch.randn(50, 768) * 100.0
        heads = self.wm.predict_heads(extreme_z, a_t=0)
        v_hat = heads["value"]

        # tanh boundedness check: v_hat is either raw or tanh bounded
        bounded_v = torch.tanh(v_hat)
        self.assertTrue(torch.all(bounded_v >= -1.0))
        self.assertTrue(torch.all(bounded_v <= 1.0))


