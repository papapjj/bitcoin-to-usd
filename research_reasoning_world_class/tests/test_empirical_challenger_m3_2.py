class TestClosedLoopContinuousCoEvolution(unittest.TestCase):
    def test_continuous_simulation_with_cloned_latent_mitigation(self):
        """
        Verifies that with the z.clone() mitigation, continuous closed-loop
        simulation runs indefinitely without any autograd or numerical errors.
        """
        policy = get_initialized_policy()
        # Isolate synthetic closed-loop simulation from ambient disk ledger sync
        policy._sync_closed_deals = lambda: None
        initial_adaptations = policy.adaptation_count
        rng = np.random.RandomState(999)
        settled_trades = 0

        for tick in range(100):
            obs = rng.randn(137).astype(np.float32) * 0.3
            obs[15] = 0.20
            if tick % 4 == 0:
                obs[120] = 1.0
                obs[129] = 0.8
            elif tick % 4 == 2:
                obs[120] = -1.0
                obs[130] = 0.8

            traces = policy.act_nam_tac_nhan(obs)
            a0 = getattr(traces[0], "action_index", getattr(traces[0], "selected_idx", 0))
            a1 = getattr(traces[1], "action_index", getattr(traces[1], "selected_idx", 0))

            if (a0 == 1 or a1 == 2) and tick % 5 == 0:
                is_win = (rng.rand() > 0.40)
                sim_profit = float(rng.uniform(60.0, 150.0) if is_win else -rng.uniform(50.0, 90.0))
                sim_mfe = float(rng.uniform(1.5, 3.0) if is_win else rng.uniform(0.1, 0.4))
                sim_mae = float(rng.uniform(0.1, 0.3) if is_win else rng.uniform(0.8, 1.2))

                # Apply mitigation: clone inference tensor before observe_transition
                if policy._last_reasoning_z is not None:
                    policy._last_reasoning_z = policy._last_reasoning_z.clone()

                adapt_res = policy.observe_transition(
                    trace=f"loop_trade_{settled_trades}",
                    next_obs=obs,
                    reward=sim_profit,
                    cost=1.50,
                    done=True,
                    pnl=sim_profit,
                    exit_type="TAKE_PROFIT" if is_win else "STOP_LOSS",
                    mfe=sim_mfe,
                    mae=sim_mae,
                )
                self.assertEqual(adapt_res["status"], "ADAPTED")
                self.assertTrue(math.isfinite(adapt_res["loss"]))
                settled_trades += 1

        self.assertGreater(settled_trades, 5)
        self.assertEqual(policy.adaptation_count - initial_adaptations, settled_trades)


