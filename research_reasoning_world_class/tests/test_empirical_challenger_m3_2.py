class TestOnlineCoEvolutionGradientsAndWeights(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.policy = get_initialized_policy()
        cls.ledger_path = ROOT / "mt5_v2_runner" / "MQL5" / "Files" / "self_growing_execution.csv"

    def test_observe_transition_isolated_deals(self):
        """
        Verify that observe_transition computes valid gradients across all target modules
        (value_head, risk_bounds_head, prm_verifier.step_evaluator) with 0 NaN and 0 Inf
        when operating on clean/unencumbered latents.
        """
        policy = get_initialized_policy()
        
        named_params = {
            "value_head": list(policy.world_model.value_head.named_parameters()),
            "risk_bounds_head": list(policy.world_model.risk_bounds_head.named_parameters()),
            "step_evaluator": list(policy.pipeline.cot_engine.prm_verifier.step_evaluator.named_parameters()),
        }

        test_deals = [
            {"pnl": 250.0, "mfe": 3.2, "mae": 0.2, "exit": "TAKE_PROFIT"},
            {"pnl": -95.0, "mfe": 0.4, "mae": 1.0, "exit": "STOP_LOSS"},
            {"pnl": 45.0, "mfe": 1.5, "mae": 0.5, "exit": "TRAILING_STOP"},
            {"pnl": -120.0, "mfe": 0.1, "mae": 1.2, "exit": "STOP_LOSS"},
            {"pnl": 310.0, "mfe": 4.0, "mae": 0.1, "exit": "TAKE_PROFIT"},
        ]

        for i, deal in enumerate(test_deals):
            policy.online_optimizer.zero_grad()

            res = policy.observe_transition(
                trace=f"deal_test_{i}",
                next_obs=np.zeros(137),
                reward=deal["pnl"],
                cost=2.0,
                done=True,
                pnl=deal["pnl"],
                exit_type=deal["exit"],
                mfe=deal["mfe"],
                mae=deal["mae"],
            )

            self.assertEqual(res["status"], "ADAPTED", f"Deal #{i} did not adapt: {res}")
            loss = res["loss"]
            self.assertTrue(math.isfinite(loss), f"Deal #{i}: loss {loss} is not finite!")
            self.assertGreater(loss, 0.0, f"Deal #{i}: loss {loss} must be > 0")

            for group_name, p_list in named_params.items():
                for p_name, param in p_list:
                    self.assertFalse(torch.isnan(param).any().item(), f"NaN in {group_name}.{p_name}")
                    self.assertFalse(torch.isinf(param).any().item(), f"Inf in {group_name}.{p_name}")

    def test_weight_displacement_norm_on_real_execution_ledger(self):
        """
        Consumes authentic closed deal records from `self_growing_execution.csv`,
        verifies that weights change measurably (||theta_t - theta_0|| > 0)
        and absolutely 0 NaN / 0 Inf arise during full co-evolution on MT5 data.
        """
        self.assertTrue(self.ledger_path.exists(), f"Ledger file not found at {self.ledger_path}")
        policy = get_initialized_policy()

        w_before = {
            "val_w0": policy.world_model.value_head[0].weight.detach().clone(),
            "val_w2": policy.world_model.value_head[2].weight.detach().clone(),
            "rb_w0": policy.world_model.risk_bounds_head[0].weight.detach().clone(),
            "rb_w2": policy.world_model.risk_bounds_head[2].weight.detach().clone(),
            "prm_w0": policy.pipeline.cot_engine.prm_verifier.step_evaluator[0].weight.detach().clone(),
            "prm_w2": policy.pipeline.cot_engine.prm_verifier.step_evaluator[2].weight.detach().clone(),
        }

        # Sync all deals from self_growing_execution.csv
        policy._last_exec_pos = 0
        policy._sync_closed_deals()

        self.assertGreater(policy.adaptation_count, 0, "No adaptations triggered from ledger!")

        displacements = {
            "val_w0": torch.norm(policy.world_model.value_head[0].weight - w_before["val_w0"], p=2).item(),
            "val_w2": torch.norm(policy.world_model.value_head[2].weight - w_before["val_w2"], p=2).item(),
            "rb_w0": torch.norm(policy.world_model.risk_bounds_head[0].weight - w_before["rb_w0"], p=2).item(),
            "rb_w2": torch.norm(policy.world_model.risk_bounds_head[2].weight - w_before["rb_w2"], p=2).item(),
            "prm_w0": torch.norm(policy.pipeline.cot_engine.prm_verifier.step_evaluator[0].weight - w_before["prm_w0"], p=2).item(),
            "prm_w2": torch.norm(policy.pipeline.cot_engine.prm_verifier.step_evaluator[2].weight - w_before["prm_w2"], p=2).item(),
        }

        # Assert no NaN/Inf in any parameters
        for k, v in displacements.items():
            self.assertGreater(v, 1e-5, f"Parameter {k} experienced zero displacement!")

    def test_adversarial_and_extreme_deal_inputs(self):
        """
        Stress-tests observe_transition against extreme / adversarial deal records:
        Massive profits, catastrophic losses, zero profit, negative MFE/MAE.
        """
        policy = get_initialized_policy()

        adversarial_cases = [
            {"pnl": 1_000_000.0, "mfe": 500.0, "mae": 0.0, "exit": "MEGA_PUMP"},
            {"pnl": -1_000_000.0, "mfe": 0.0, "mae": 500.0, "exit": "FLASH_CRASH"},
            {"pnl": 0.0, "mfe": 0.0, "mae": 0.0, "exit": "SCRATCH"},
            {"pnl": 0.001, "mfe": 0.01, "mae": 0.01, "exit": "MICRO_WIN"},
            {"pnl": -0.001, "mfe": 0.01, "mae": 0.01, "exit": "MICRO_LOSS"},
            {"pnl": 50.0, "mfe": -10.0, "mae": -10.0, "exit": "NEGATIVE_BOUNDS"},
        ]

        for idx, case in enumerate(adversarial_cases):
            res = policy.observe_transition(
                trace=f"adv_case_{idx}",
                next_obs=np.zeros(137),
                reward=case["pnl"],
                cost=0.0,
                done=True,
                pnl=case["pnl"],
                exit_type=case["exit"],
                mfe=case["mfe"],
                mae=case["mae"],
            )
            for name, param in policy.world_model.value_head.named_parameters():
                self.assertFalse(torch.isnan(param).any().item())
                self.assertFalse(torch.isinf(param).any().item())

    def test_inference_mode_tensor_backward_bug(self):
        """
        CRITICAL BUG REPRODUCTION:
        Demonstrates that when act_nam_tac_nhan runs, _last_reasoning_z receives
        an inference tensor from pipeline.process_tick (is_inference() == True).
        Calling observe_transition directly without cloning raises:
        RuntimeError: Inference tensors cannot be saved for backward.
        And applying z.clone() immediately eliminates the defect.
        """
        policy = get_initialized_policy()
        obs = np.zeros(137, dtype=np.float32)
        
        # 1. Process 1 tick so _last_reasoning_z is populated from pipeline
        _ = policy.act_nam_tac_nhan(obs)
        self.assertIsNotNone(policy._last_reasoning_z)
        self.assertFalse(policy._last_reasoning_z.is_inference(), "Expected _last_reasoning_z to be cloned non-inference tensor")

        # 2. Confirm RuntimeError is eliminated by the remediation fix in observe_transition
        try:
            res = policy.observe_transition(
                trace="test_uncloned",
                next_obs=obs,
                reward=100.0,
                cost=1.0,
                done=True,
                pnl=100.0,
                exit_type="TAKE_PROFIT",
                mfe=2.0,
                mae=0.1
            )
            self.assertEqual(res.get("status"), "ADAPTED")
        except RuntimeError as e:
            self.fail(f"observe_transition raised unexpected RuntimeError: {e}")

        # 3. Prove that cloning / autograd produces valid non-zero loss and updates weights
        self.assertGreater(policy.adaptation_count, 0)
        self.assertGreater(policy.last_adapted_loss, 0.0)
        self.assertFalse(policy._last_reasoning_z.is_inference())
        res = policy.observe_transition(
            trace="test_cloned_fix",
            next_obs=obs,
            reward=100.0,
            cost=1.0,
            done=True,
            pnl=100.0,
            exit_type="TAKE_PROFIT",
            mfe=2.0,
            mae=0.1
        )
        self.assertEqual(res["status"], "ADAPTED")
        self.assertTrue(math.isfinite(res["loss"]))


