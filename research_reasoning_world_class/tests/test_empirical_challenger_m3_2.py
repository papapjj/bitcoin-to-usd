class TestTradeGenerationAndGeometryAcross4Regimes(unittest.TestCase):
    def generate_regime_observations(self, regime: str, n_ticks: int = 100, seed: int = 42) -> np.ndarray:
        rng = np.random.RandomState(seed)
        obs = np.zeros((n_ticks, 137), dtype=np.float32)

        for i in range(n_ticks):
            v = rng.randn(137).astype(np.float32) * 0.1
            v[15] = 0.20
            v[78] = float(np.sin(i * 0.05))
            v[79] = float(np.cos(i * 0.05))

            if regime == "trending":
                trend_dir = 1.0 if i < n_ticks // 2 else -1.0
                v[0] = trend_dir * float(rng.uniform(0.5, 1.5))
                v[7] = trend_dir * float(rng.uniform(0.4, 1.2))
                v[8] = float(rng.uniform(0.05, 0.2))
                v[9] = float(rng.uniform(0.05, 0.2))
                v[10] = abs(v[7]) + v[8] + v[9]
                v[81] = trend_dir * float(rng.uniform(0.02, 0.05))
                v[85] = trend_dir * float(rng.uniform(0.03, 0.06))
                v[89] = trend_dir * float(rng.uniform(0.04, 0.08))
                v[120] = trend_dir * 0.2
                v[121] = float(rng.uniform(1.0, 2.5))

            elif regime == "sideway":
                v[0] = float(np.sin(i * 0.8) * 0.15)
                v[7] = float(np.sin(i * 0.8) * 0.10)
                v[8] = float(rng.uniform(0.05, 0.15))
                v[9] = float(rng.uniform(0.05, 0.15))
                v[10] = abs(v[7]) + v[8] + v[9]
                v[81] = float(np.sin(i * 0.2) * 0.002)
                v[85] = float(np.sin(i * 0.1) * 0.003)
                v[89] = float(np.sin(i * 0.05) * 0.004)
                v[120] = float(np.sin(i * 0.5) * 0.1)
                v[121] = float(rng.uniform(0.5, 1.2))

            elif regime == "volatile_sweep":
                is_bull_sweep = (i % 2 == 0)
                v[0] = float(rng.randn() * 0.3)
                v[7] = float(rng.randn() * 0.2)
                v[8] = float(rng.uniform(1.5, 4.0))
                v[9] = float(rng.uniform(1.5, 4.0))
                v[10] = abs(v[7]) + v[8] + v[9]
                v[15] = float(rng.uniform(0.3, 0.8))
                if is_bull_sweep:
                    v[120] = float(rng.uniform(0.5, 1.0))
                    v[129] = float(rng.uniform(0.4, 0.9))
                    v[130] = 0.0
                    v[81] = 0.01
                else:
                    v[120] = float(rng.uniform(-1.0, -0.5))
                    v[129] = 0.0
                    v[130] = float(rng.uniform(0.4, 0.9))
                    v[81] = -0.01
                v[121] = float(rng.uniform(2.0, 6.0))

            elif regime == "breakout_expansion":
                direction = 1.0 if (i // 25) % 2 == 0 else -1.0
                v[0] = direction * float(rng.uniform(2.0, 5.0))
                v[7] = direction * float(rng.uniform(1.8, 4.5))
                v[8] = float(rng.uniform(0.1, 0.4))
                v[9] = float(rng.uniform(0.1, 0.4))
                v[10] = abs(v[7]) + v[8] + v[9]
                v[81] = direction * float(rng.uniform(0.04, 0.10))
                v[85] = direction * float(rng.uniform(0.05, 0.12))
                v[89] = direction * float(rng.uniform(0.05, 0.15))
                v[120] = direction * 0.8
                v[121] = float(rng.uniform(5.0, 15.0))

            obs[i] = v
        return obs

    def test_regime_geometry_and_governor_invariants(self):
        """
        Tests order geometry, Governor HOLD invariant, and active trade triggers
        across 400 ticks (100 ticks per regime).
        """
        policy = get_initialized_policy()
        regimes = ["trending", "sideway", "volatile_sweep", "breakout_expansion"]
        ticks_per_regime = 100

        all_violations = []
        total_trades = 0
        regime_trade_counts = {}

        for reg in regimes:
            obs_array = self.generate_regime_observations(reg, n_ticks=ticks_per_regime, seed=123)
            reg_trades = 0

            for tick in range(ticks_per_regime):
                obs = obs_array[tick]
                traces = policy.act_nam_tac_nhan(obs)

                # 1. Governor Invariant Check (Agent 4)
                agent4_trace = traces[4]
                agent4_out = getattr(agent4_trace, "output_vector", getattr(agent4_trace, "selected_action", None))
                if agent4_out is not None:
                    if agent4_out[19] != 0.0:
                        all_violations.append(f"{reg} tick {tick}: wire[19] = {agent4_out[19]}")
                    if agent4_out[0] != 1.0:
                        all_violations.append(f"{reg} tick {tick}: wire[0] = {agent4_out[0]}")

                # 2. Order Geometry Check
                a0 = getattr(traces[0], "action_index", getattr(traces[0], "selected_idx", 0))
                a1 = getattr(traces[1], "action_index", getattr(traces[1], "selected_idx", 0))
                t0_details = getattr(traces[0], "action_details", {}) or {}
                t1_details = getattr(traces[1], "action_details", {}) or {}

                if a0 == 1 or a1 == 2:
                    reg_trades += 1
                    total_trades += 1
                    sl = float(t0_details.get("sl_atr", 1.0) if a0 == 1 else t1_details.get("sl_atr", 1.0))
                    tp_atr = float(t0_details.get("tp_atr", 0.0) if a0 == 1 else t1_details.get("tp_atr", 0.0))
                    tp_rr = tp_atr / max(1e-4, sl)

                    # Geometries must match one of the 3 specified archetypes:
                    # Counter-Trap: SL 1.0 ATR, TP RR 3.0
                    # Tier 1 Scalp: SL 2.0 ATR, TP RR 1.50 or 0.60
                    # Tier 2 Sniper: SL 2.5 ATR, TP RR 1.50 (or SL 2.0, TP RR 5.0)
                    is_valid_geom = (
                        (abs(sl - 1.0) < 0.1 and abs(tp_rr - 3.0) < 0.1) or
                        (abs(sl - 2.0) < 0.1 and (abs(tp_rr - 1.5) < 0.1 or abs(tp_rr - 0.6) < 0.1 or abs(tp_rr - 5.0) < 0.1)) or
                        (abs(sl - 2.5) < 0.1 and (abs(tp_rr - 1.5) < 0.1 or abs(tp_rr - 2.0) < 0.1))
                    )
                    self.assertTrue(is_valid_geom, f"{reg} tick {tick}: Invalid geometry sl={sl}, tp_rr={tp_rr}")

            regime_trade_counts[reg] = reg_trades

        # Assertions
        self.assertEqual(len(all_violations), 0, f"Found {len(all_violations)} Governor violations!")
        # Trade rate check: across 400 ticks, trade count should easily exceed 80 (scaling to > 300 / 1440 ticks)
        self.assertGreater(total_trades, 80, f"Total trades {total_trades} too low!")
        for reg, count in regime_trade_counts.items():
            self.assertGreater(count, 5, f"Regime {reg} starved of trades: count={count}")


